"""Create only the mirror's assets and add one mirror surface at the existing house mirror."""
import unreal

tools = unreal.AssetToolsHelpers.get_asset_tools()
edit = unreal.MaterialEditingLibrary

def asset(name, path, cls, factory):
    return unreal.load_asset(path + '/' + name) or tools.create_asset(name, path, cls, factory)

target = asset('RT_MirrorFallback', '/Game/Items/Mirror', unreal.TextureRenderTarget2D, unreal.TextureRenderTargetFactoryNew())
target.set_editor_property('size_x', 128)
target.set_editor_property('size_y', 128)
target.set_editor_property('render_target_format', unreal.TextureRenderTargetFormat.RTF_RGBA16F)
target.set_editor_property('clear_color', unreal.LinearColor(0.015, 0.018, 0.022, 1))
material = asset('M_Mirror', '/Game/Items/Mirror', unreal.Material, unreal.MaterialFactoryNew())
edit.delete_all_material_expressions(material)
material.set_editor_property('shading_model', unreal.MaterialShadingModel.MSM_UNLIT)
material.set_editor_property('two_sided', False)
screen = edit.create_material_expression(material, unreal.MaterialExpressionScreenPosition, -700, 0)
x = edit.create_material_expression(material, unreal.MaterialExpressionComponentMask, -500, 0)
x.set_editor_property('r', True); x.set_editor_property('g', False)
y = edit.create_material_expression(material, unreal.MaterialExpressionComponentMask, -500, 160)
y.set_editor_property('r', False); y.set_editor_property('g', True)
flip = edit.create_material_expression(material, unreal.MaterialExpressionOneMinus, -300, 0)
uv = edit.create_material_expression(material, unreal.MaterialExpressionAppendVector, -100, 0)
texture = edit.create_material_expression(material, unreal.MaterialExpressionTextureSampleParameter2D, 100, 0)
texture.set_editor_property('parameter_name', 'ReflectionTexture')
texture.set_editor_property('texture', target)
texture.set_editor_property('sampler_type', unreal.MaterialSamplerType.SAMPLERTYPE_LINEAR_COLOR)
assert edit.connect_material_expressions(screen, 'ViewportUV', x, '')
assert edit.connect_material_expressions(screen, 'ViewportUV', y, '')
assert edit.connect_material_expressions(x, '', flip, '')
assert edit.connect_material_expressions(flip, '', uv, 'A')
assert edit.connect_material_expressions(y, '', uv, 'B')
assert edit.connect_material_expressions(uv, '', texture, '')
enabled = edit.create_material_expression(material, unreal.MaterialExpressionScalarParameter, 100, 220)
enabled.set_editor_property('parameter_name', 'ReflectionEnabled')
enabled.set_editor_property('default_value', 1.0)
active = edit.create_material_expression(material, unreal.MaterialExpressionMultiply, 350, 0)
assert edit.connect_material_expressions(texture, 'RGB', active, 'A')
assert edit.connect_material_expressions(enabled, '', active, 'B')
assert edit.connect_material_property(active, '', unreal.MaterialProperty.MP_EMISSIVE_COLOR)
edit.recompile_material(material)

frame = asset('M_MirrorFrame', '/Game/Items/Mirror', unreal.Material, unreal.MaterialFactoryNew())
edit.delete_all_material_expressions(frame)
color = edit.create_material_expression(frame, unreal.MaterialExpressionConstant3Vector)
color.set_editor_property('constant', unreal.LinearColor(0.25, 0.11, 0.035, 1))
edit.connect_material_property(color, '', unreal.MaterialProperty.MP_BASE_COLOR)
for prop, value in [(unreal.MaterialProperty.MP_METALLIC, .65), (unreal.MaterialProperty.MP_ROUGHNESS, .3)]:
    node = edit.create_material_expression(frame, unreal.MaterialExpressionConstant)
    node.set_editor_property('r', value)
    edit.connect_material_property(node, '', prop)
edit.recompile_material(frame)

factory = unreal.DataAssetFactory()
factory.set_editor_property('data_asset_class', unreal.TBMirrorData)
data = asset('DA_Mirror', '/Game/Data', unreal.TBMirrorData, factory)
data.set_editor_property('mirror_material', material)
data.set_editor_property('frame_material', frame)
for obj in [target, material, frame, data]:
    assert unreal.EditorAssetLibrary.save_loaded_asset(obj)

factory = unreal.BlueprintFactory()
factory.set_editor_property('parent_class', unreal.TBMirror)
blueprint = asset('BP_Mirror', '/Game/Items/Mirror', unreal.Blueprint, factory)
unreal.BlueprintEditorLibrary.compile_blueprint(blueprint)
assert unreal.EditorAssetLibrary.save_loaded_asset(blueprint)

world = unreal.EditorLoadingAndSavingUtils.load_map('/Game/Maps/TB_StylizedHouse')
actors = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
existing = [a for a in actors.get_all_level_actors() if isinstance(a, unreal.TBMirror)]
assert len(existing) <= 1
mirror = existing[0] if existing else actors.spawn_actor_from_class(unreal.TBMirror, unreal.Vector(446, -460.68, 164.42))
mirror.set_actor_location_and_rotation(unreal.Vector(446, -460.68, 164.42), unreal.Rotator(yaw=180), False, True)
mirror.set_actor_scale3d(unreal.Vector(1, .8, 1.5))
mirror.set_actor_label('Mirror_Hallway')
mirror.set_folder_path('Gameplay/Mirrors')
mirror.set_editor_property('mirror_data', data)
assert unreal.EditorLoadingAndSavingUtils.save_map(world, '/Game/Maps/TB_StylizedHouse')
print('MIRROR_ASSETS_AND_PLACEMENT_SAVED')
